@pytest.mark.anyio
async def test_agent_writes_land_in_the_graph_without_review(
    client: TestClient, mcp_server, auto_approve
) -> None:
    course = create_course(client, "EX106")
    document = upload(client, course["id"])

    async with Client(mcp_server) as mcp_client:
        first = await mcp_client.call_tool(
            "create_candidate_node",
            {
                "course_id": course["id"],
                "node_type": "CONCEPT",
                "label": "Cyclic group",
                **evidence(document["id"]),
            },
        )
        second = await mcp_client.call_tool(
            "create_candidate_node",
            {
                "course_id": course["id"],
                "node_type": "CONCEPT",
                "label": "Generator",
                **evidence(document["id"]),
            },
        )
        await mcp_client.call_tool(
            "create_candidate_relationship",
            {
                "course_id": course["id"],
                "source_node_id": first.structured_content["id"],
                "target_node_id": second.structured_content["id"],
                "relationship_type": "REQUIRES",
                **evidence(document["id"]),
            },
        )

    assert first.structured_content["review_status"] == "APPROVED"
    graph = client.get(f"/courses/{course['id']}/graph").json()
    assert sorted(node["label"] for node in graph["nodes"]) == ["Cyclic group", "Generator"]
    assert len(graph["edges"]) == 1
    queue = client.get(f"/courses/{course['id']}/graph/review/candidates").json()
    assert queue["pendingCount"] == 0


@pytest.mark.anyio
async def test_re_extraction_folds_into_existing_nodes_instead_of_duplicating(
    client: TestClient, mcp_server, auto_approve
) -> None:
    course = create_course(client, "EX107")
    first_document = upload(client, course["id"], "week-5.md")
    second_document = upload(client, course["id"], "week-6.md")

    async with Client(mcp_server) as mcp_client:
        original = await mcp_client.call_tool(
            "create_candidate_node",
            {
                "course_id": course["id"],
                "node_type": "CONCEPT",
                "label": "Cyclic group",
                **evidence(first_document["id"]),
            },
        )
        repeat = await mcp_client.call_tool(
            "create_candidate_node",
            {
                "course_id": course["id"],
                "node_type": "CONCEPT",
                "label": "cyclic   group",
                "description": "Generated by a single element.",
                **evidence(second_document["id"], "Every cyclic group is abelian."),
            },
        )

    assert repeat.structured_content["id"] == original.structured_content["id"]
    graph = client.get(f"/courses/{course['id']}/graph").json()
    assert [node["label"] for node in graph["nodes"]] == ["Cyclic group"]
    with SessionLocal() as db:
        node = db.get(GraphNode, original.structured_content["id"])
        assert node.description == "Generated by a single element."
        assert db.query(GraphEvidence).filter_by(graph_node_id=node.id).count() == 2
        assert {
            item.document_id
            for item in db.query(GraphEvidence).filter_by(graph_node_id=node.id).all()
        } == {first_document["id"], second_document["id"]}


@pytest.mark.anyio
async def test_repeated_relationships_do_not_duplicate_edges(
    client: TestClient, mcp_server, auto_approve
) -> None:
    course = create_course(client, "EX108")
    document = upload(client, course["id"])

    async with Client(mcp_server) as mcp_client:
        source = await mcp_client.call_tool(
            "create_candidate_node",
            {
                "course_id": course["id"],
                "node_type": "CONCEPT",
                "label": "Cyclic group",
                **evidence(document["id"]),
            },
        )
        target = await mcp_client.call_tool(
            "create_candidate_node",
            {
                "course_id": course["id"],
                "node_type": "CONCEPT",
                "label": "Group",
                **evidence(document["id"]),
            },
        )
        payload = {
            "course_id": course["id"],
            "source_node_id": source.structured_content["id"],
            "target_node_id": target.structured_content["id"],
            "relationship_type": "REQUIRES",
            **evidence(document["id"]),
        }
        first = await mcp_client.call_tool("create_candidate_relationship", payload)
        second = await mcp_client.call_tool("create_candidate_relationship", payload)

    assert first.structured_content["id"] == second.structured_content["id"]
    assert len(client.get(f"/courses/{course['id']}/graph").json()["edges"]) == 1


