def create_course(client: TestClient, code: str) -> dict[str, Any]:
    response = client.post("/courses", json={"name": f"Course {code}", "code": code})
    assert response.status_code == 201
    return response.json()


def upload(client: TestClient, course_id: str, name: str = "lecture.md") -> dict[str, Any]:
    response = client.post(
        f"/courses/{course_id}/documents",
        data={"document_type": "LECTURE"},
        files={
            "file": (
                name,
                b"# Groups\n\nA cyclic group is generated by one element.\n",
                "text/markdown",
            )
        },
    )
    assert response.status_code == 201
    return response.json()


def evidence(
    document_id: str, excerpt: str = "A cyclic group is generated by one element."
) -> dict[str, Any]:
    return {
        "document_id": document_id,
        "source_location": {"page": 1, "section": "Groups"},
        "excerpt": excerpt,
        "confidence": 0.8,
    }


# Tool detection and settings ------------------------------------------------


def test_detect_tools_reports_every_known_agent_cli() -> None:
    tools = {tool["id"]: tool for tool in detect_tools()}
    assert {"claude", "codex", "gemini", "opencode", "cursor-agent"} <= set(tools)
    for tool in tools.values():
        assert tool["available"] is (tool["path"] is not None)
        assert "{prompt}" in tool["default_command"]


def test_extraction_settings_expose_detected_tools(client: TestClient) -> None:
    settings = client.get("/settings/extraction")
    assert settings.status_code == 200
    body = settings.json()
    assert body["enabled"] is True
    assert {tool["id"] for tool in body["tools"]} >= {"claude", "codex"}
    assert all("defaultCommand" in tool for tool in body["tools"])


def test_extraction_settings_can_be_changed_and_reset(client: TestClient) -> None:
    updated = client.put(
        "/settings/extraction",
        json={"toolId": "codex", "command": "codex exec {prompt}", "enabled": False},
    )
    assert updated.status_code == 200
    assert updated.json()["toolId"] == "codex"
    assert updated.json()["command"] == "codex exec {prompt}"
    assert updated.json()["enabled"] is False

    cleared = client.put("/settings/extraction", json={"command": ""})
    assert cleared.status_code == 200
    assert cleared.json()["commandOverride"] is None
    assert cleared.json()["command"] == AGENT_TOOLS_BY_ID["codex"].command

    assert client.put("/settings/extraction", json={"toolId": "nope"}).status_code == 422
    assert client.put("/settings/extraction", json={}).status_code == 422


# Running the agent ----------------------------------------------------------


def test_mcp_config_exposes_only_arc_with_auto_approval(tmp_path: Path) -> None:
    import json

    config = json.loads(build_mcp_config(tmp_path).read_text(encoding="utf-8"))
    assert list(config["mcpServers"]) == ["arc"]
    assert config["mcpServers"]["arc"]["env"]["ARC_AUTO_APPROVE"] == "1"
    assert config["mcpServers"]["arc"]["env"]["DATABASE_URL"] == get_settings().database_url


def test_render_command_substitutes_the_document_under_extraction(tmp_path: Path) -> None:
    command = render_command(
        'claude -p "{prompt}" --mcp-config "{mcp_config}"',
        course_id="course-1",
        document_id="document-1",
        mcp_config=tmp_path / "arc-mcp.json",
    )
    assert "course-1" in command
    assert "document-1" in command
    assert "arc-mcp.json" in command


def test_run_extraction_requires_a_configured_and_installed_command() -> None:
    with pytest.raises(ExtractionUnavailable):
        run_extraction(command_template="  ", course_id="c", document_id="d")
    with pytest.raises(ExtractionUnavailable, match="not installed"):
        run_extraction(
            command_template="arc-not-a-real-agent {prompt}", course_id="c", document_id="d"
        )


def test_run_extraction_reports_a_failing_agent() -> None:
    def failing(argv, cwd):
        return subprocess.CompletedProcess(argv, 3, "", "model refused")

    with pytest.raises(ExtractionFailed, match="model refused"):
        run_extraction(
            command_template="python {prompt}",
            course_id="c",
            document_id="d",
            runner=failing,
        )


def test_run_extraction_reports_a_timeout() -> None:
    def slow(argv, cwd):
        raise subprocess.TimeoutExpired(argv, 1)

    with pytest.raises(ExtractionFailed, match="did not finish"):
        run_extraction(
            command_template="python {prompt}", course_id="c", document_id="d", runner=slow
        )


