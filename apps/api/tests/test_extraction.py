def test_a_failing_agent_is_reported_and_retryable(client: TestClient, monkeypatch) -> None:
    course = create_course(client, "EX103")
    document = upload(client, course["id"])

    def failing(**kwargs):
        raise ExtractionFailed("claude exited with code 1: rate limited")

    monkeypatch.setattr(extraction_service, "run_extraction", failing)
    failed = client.post(f"/courses/{course['id']}/documents/{document['id']}/extract")
    assert failed.json()["extractionStatus"] == "FAILED"
    assert "rate limited" in failed.json()["extractionError"]

    monkeypatch.setattr(
        extraction_service,
        "run_extraction",
        lambda **kwargs: extraction_service.ExtractionResult(command="agent", output=""),
    )
    retried = client.post(f"/courses/{course['id']}/documents/{document['id']}/extract")
    assert retried.json()["extractionStatus"] == "COMPLETED"
    assert retried.json()["extractionError"] is None


